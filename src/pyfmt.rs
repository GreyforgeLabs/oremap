    fn json_strings_are_ascii_escaped() {
        let mut out = String::new();
        push_json_string(&mut out, "a\"\\\n\u{7f}é😀");
        assert_eq!(out, "\"a\\\"\\\\\\n\\u007f\\u00e9\\ud83d\\ude00\"");
    }

