//! Small text helpers that reproduce the Python string semantics the 0.3.x
//! implementation relied on (`str.isspace`, `str.split`, `str.splitlines`,
//! `repr`, `json.dumps(ensure_ascii=True)`, `int()` and `float()` parsing).
//!
//! Keeping these in one place lets the rest of the crate stay byte-for-byte
//! compatible with the reports and messages produced by earlier releases.

use std::fmt::Write as _;

/// `str.isspace()` / regex `\s` for `str` patterns.
pub fn is_space(c: char) -> bool {
    matches!(
        c,
        '\u{09}'..='\u{0d}'
            | '\u{1c}'..='\u{20}'
            | '\u{85}'
            | '\u{a0}'
            | '\u{1680}'
            | '\u{2000}'..='\u{200a}'
            | '\u{2028}'
            | '\u{2029}'
            | '\u{202f}'
            | '\u{205f}'
            | '\u{3000}'
    )
}

