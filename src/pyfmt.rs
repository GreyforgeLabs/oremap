/// Regex `\d` for `str` patterns (`str.isdecimal()`).
pub fn is_decimal(c: char) -> bool {
    c.is_ascii_digit() || (!c.is_ascii() && in_ranges(&DECIMAL_DIGITS, c))
}

/// Whether `c` falls in one of the sorted, inclusive `ranges`.
fn in_ranges(ranges: &[(u32, u32)], c: char) -> bool {
    let code = c as u32;
    ranges
        .binary_search_by(|&(start, end)| {
            if end < code {
                std::cmp::Ordering::Less
            } else if start > code {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// `str.strip()` with no arguments.
pub fn strip(s: &str) -> &str {
    s.trim_matches(is_space)
}

/// `str.split()` with no arguments.
pub fn split(s: &str) -> Vec<&str> {
    s.split(is_space).filter(|part| !part.is_empty()).collect()
}

fn is_line_break(c: char) -> bool {
    matches!(
        c,
        '\n' | '\u{0b}'
            | '\u{0c}'
            | '\r'
            | '\u{1c}'
            | '\u{1d}'
            | '\u{1e}'
            | '\u{85}'
            | '\u{2028}'
            | '\u{2029}'
    )
}

/// `str.splitlines()` without `keepends`.
pub fn splitlines(s: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let bytes = s.as_bytes();
    let mut start = 0;
    let mut iter = s.char_indices().peekable();
    while let Some((index, c)) = iter.next() {
        if is_line_break(c) {
            lines.push(&s[start..index]);
            let mut next = index + c.len_utf8();
            if c == '\r' && bytes.get(next) == Some(&b'\n') {
                iter.next();
                next += 1;
            }
            start = next;
        }
    }
    if start < s.len() {
        lines.push(&s[start..]);
    }
    lines
}

/// Return at most `limit` characters (Python `text[:limit]`).
pub fn take_chars(s: &str, limit: usize) -> &str {
    match s.char_indices().nth(limit) {
        Some((index, _)) => &s[..index],
        None => s,
    }
}

/// Character length (Python `len(str)`).
pub fn char_len(s: &str) -> usize {
    s.chars().count()
}

/// `bytes.decode("utf-8", errors="ignore")`.
pub fn decode_ignore(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len());
    let mut rest = bytes;
    loop {
        match std::str::from_utf8(rest) {
            Ok(valid) => {
                out.push_str(valid);
                return out;
            }
            Err(error) => {
                let valid = error.valid_up_to();
                out.push_str(std::str::from_utf8(&rest[..valid]).unwrap_or_default());
                let skip = error.error_len().unwrap_or(rest.len() - valid);
                rest = &rest[valid + skip..];
            }
        }
    }
}

/// Decode captured subprocess output the way `subprocess.run(text=True)`
/// presents it: UTF-8 text with universal newlines (`\r\n` and `\r` become
/// `\n`). Invalid UTF-8 is replaced instead of raising.
pub fn decode_process_text(bytes: &[u8]) -> String {
    let text = String::from_utf8_lossy(bytes);
    if !text.contains('\r') {
        return text.into_owned();
    }
    text.replace("\r\n", "\n").replace('\r', "\n")
}

