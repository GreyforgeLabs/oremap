/// Regex `\w` for `str` patterns: `str.isalnum()` or `_`.
pub fn is_word(c: char) -> bool {
    if c == '_' {
        return true;
    }
    if !c.is_alphanumeric() {
        return false;
    }
    !in_ranges(&NOT_PYTHON_WORD, c)
}

